# ============================================================
# 数据模型
# ============================================================

@dataclass
class SimulatorInstance:
    """单个模拟器实例"""
    product: str           # ECLIPSE_100 / ECLIPSE_300 / INTERSECT / ...
    exe_path: str          # 完整可执行文件路径
    version: Optional[str] = None        # 2022.2
    build: Optional[str] = None         # 20220711.4
    arch: Optional[str] = None          # pc_x86_64 / pc_x86_64e / pc_win32
    install_root: Optional[str] = None  # C:\\ecl\\2022.2
    source: str = "unknown"            # registry / common_path / filesystem_deep / env
    file_size_mb: Optional[float] = None

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class LicenseStatus:
    """License 状态"""
    env_vars: Dict[str, str] = field(default_factory=dict)
    server_port: Optional[int] = None
    server_host: Optional[str] = None
    license_type: Optional[str] = None  # 'network' / 'node_locked' / 'unknown'
    lmutil_path: Optional[str] = None
    lmstat_summary: Optional[str] = None
    smoke_test_results: Dict[str, dict] = field(default_factory=dict)
    overall_status: str = "unknown"     # 'ok' / 'no_license' / 'unknown'

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class DetectionReport:
    """完整检测报告"""
    scan_time: str
    hostname: str
    os_version: str
    python_version: str
    simulators: List[dict] = field(default_factory=list)
    license: dict = field(default_factory=dict)
    scan_stats: dict = field(default_factory=dict)
    warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)


# ============================================================
# 检测器主类
# ============================================================

class SimulatorDetector:
    """模拟器检测器"""

    def __init__(self, verbose: bool = False, deep: bool = False,
                 extra_roots: Optional[List[str]] = None):
        self.verbose = verbose
        self.deep = deep
        self.extra_roots = extra_roots or []
        self.simulators: List[SimulatorInstance] = []
        self.license = LicenseStatus()
        self.scan_stats = {
            'registry_hits': 0,
            'common_path_hits': 0,
            'filesystem_hits': 0,
            'env_hits': 0,
            'duplicate_removed': 0,
            'smoke_test_runs': 0,
            'duration_sec': 0.0,
        }
        self.warnings: List[str] = []

    def log(self, msg: str):
        if self.verbose:
            print(f"  [*] {msg}", file=sys.stderr)

    # ------------------------------------------------------------
    # 主流程
    # ------------------------------------------------------------

    def detect_all(self) -> 'SimulatorDetector':
        """执行全部检测"""
        t0 = time.time()
        self.log("=== 第 1 层：环境变量 ===")
        self._search_env()

        self.log("=== 第 2 层：注册表 ===")
        self._search_registry()

        self.log("=== 第 3 层：常见路径 ===")
        self._search_common_paths()

        if self.deep:
            self.log("=== 第 4 层：全盘深度搜索 ===")
            self._search_filesystem_deep()

        self.log("=== 去重与版本补全 ===")
        self._dedup()
        self._enrich_versions_from_path()
        self._enrich_versions_from_file_info()

        self.log("=== License 探测 ===")
        self._check_license_env()
        self._check_lmutil()

        self.scan_stats['duration_sec'] = round(time.time() - t0, 2)
        return self

    # ------------------------------------------------------------
    # 检索 1：环境变量 PATH
    # ------------------------------------------------------------

    def _search_env(self):
        """从 PATH 环境变量中查找模拟器"""
        path = os.environ.get('PATH', '')
        for p in path.split(os.pathsep):
            if not p:
                continue
            pp = Path(p)
            try:
                for exe in pp.glob('*.exe'):
                    if exe.name.lower() in TARGET_EXE_NAMES:
                        sim = self._identify_exe(exe, source='env')
                        if sim:
                            self.simulators.append(sim)
                            self.scan_stats['env_hits'] += 1
                            self.log(f"env: {exe}")
            except (PermissionError, OSError):
                continue

    # ------------------------------------------------------------
    # 检索 2：注册表
    # ------------------------------------------------------------

    def _search_registry(self):
        """查询 Windows 注册表已安装程序"""
        if not winreg:
            self.warnings.append("非 Windows 平台，跳过注册表查询")
            return

        for root, subkey in REGISTRY_UNINSTALL_KEYS:
            try:
                with winreg.OpenKey(root, subkey) as k:
                    n_sub = winreg.QueryInfoKey(k)[0]
                    for i in range(n_sub):
                        try:
                            subname = winreg.EnumKey(k, i)
                            with winreg.OpenKey(k, subname) as sk:
                                name = self._reg_get(sk, "DisplayName")
                                if not name or not REGISTRY_NAME_PATTERN.search(name):
                                    continue
                                loc = self._reg_get(sk, "InstallLocation")
                                ver = self._reg_get(sk, "DisplayVersion")
                                if loc:
                                    self.log(f"registry: {name} -> {loc}")
                                    self.scan_stats['registry_hits'] += 1
                                    self._scan_dir_for_exes(Path(loc), source='registry')
                        except OSError:
                            continue
            except OSError:
                continue

    @staticmethod
    def _reg_get(key, name: str) -> Optional[str]:
        try:
            val, _ = winreg.QueryValueEx(key, name)
            return str(val) if val else None
        except (FileNotFoundError, OSError):
            return None

    # ------------------------------------------------------------
    # 检索 3：常见安装路径
    # ------------------------------------------------------------

    def _search_common_paths(self):
        roots = list(COMMON_INSTALL_ROOTS) + list(self.extra_roots)
        for root in roots:
            p = Path(root)
            if not p.exists():
                continue
            self.log(f"common: 扫描 {p}")
            found_before = len(self.simulators)
            self._scan_dir_for_exes(p, source='common_path', maxdepth=6)
            self.scan_stats['common_path_hits'] += len(self.simulators) - found_before

    # ------------------------------------------------------------
    # 检索 4：全盘深度搜索（用 PowerShell 加速）
    # ------------------------------------------------------------

    def _search_filesystem_deep(self, drives: Optional[List[str]] = None):
        if drives is None:
            drives = ['C:', 'D:', 'E:']

        # PowerShell Get-ChildItem 比 Python os.walk 快得多
        for drive in drives:
            drive_path = Path(drive + '\\')
            if not drive_path.exists():
                continue
            self.log(f"deep: 全盘搜索 {drive}")
            try:
                # 用 PowerShell 加速
                ps_script = (
                    f"Get-ChildItem -Path '{drive}\\' -Recurse -Depth 5 -Filter '*.exe' "
                    f"-ErrorAction SilentlyContinue | "
                    f"Where-Object {{ $_.Name -match '^(eclipse|e300|intersect|ix|frontsim|visage|petrel|eclrun)(_[a-z]+)?\\.exe$' }} | "
                    f"ForEach-Object {{ $_.FullName }}"
                )
                r = subprocess.run(
                    ['powershell', '-NoProfile', '-NonInteractive', '-Command', ps_script],
                    capture_output=True, text=True, timeout=300
                )
                if r.returncode == 0:
                    for line in r.stdout.strip().split('\n'):
                        line = line.strip()
                        if not line:
                            continue
                        exe = Path(line)
                        if exe.name.lower() in TARGET_EXE_NAMES and exe.exists():
                            sim = self._identify_exe(exe, source='filesystem_deep')
                            if sim:
                                self.simulators.append(sim)
                                self.scan_stats['filesystem_hits'] += 1
                                self.log(f"deep: {exe}")
            except subprocess.TimeoutExpired:
                self.warnings.append(f"深度搜索 {drive} 超时")
            except Exception as e:
                self.warnings.append(f"深度搜索 {drive} 失败: {e}")

    # ------------------------------------------------------------
    # 通用：在目录中递归查找目标 exe
    # ------------------------------------------------------------

    def _scan_dir_for_exes(self, root: Path, source: str, maxdepth: int = 6):
        if not root.exists():
            return
        try:
            for exe in root.rglob('*.exe'):
                if exe.name.lower() in TARGET_EXE_NAMES:
                    sim = self._identify_exe(exe, source=source)
                    if sim:
                        self.simulators.append(sim)
                        self.log(f"{source}: {exe}")
        except (PermissionError, OSError):
            pass

    # ------------------------------------------------------------
    # 识别单个 exe → SimulatorInstance
    # ------------------------------------------------------------

    def _identify_exe(self, exe: Path, source: str) -> Optional[SimulatorInstance]:
        for pattern, product in PRODUCT_RULES:
            if pattern.match(exe.name):
                version, install_root, arch = self._infer_version_and_root(exe)
                try:
                    size_mb = round(exe.stat().st_size / 1024 / 1024, 2)
                except OSError:
                    size_mb = None
                return SimulatorInstance(
                    product=product,
                    exe_path=str(exe).replace('/', '\\'),
                    version=version,
                    arch=arch,
                    install_root=install_root,
                    source=source,
                    file_size_mb=size_mb,
                )
        return None

    @staticmethod
    def _infer_version_and_root(exe: Path):
        """从路径中提取版本、安装根、架构

        典型路径:
          C:\\ecl\\2022.2\\bin\\pc_x86_64\\eclipse.exe
          C:\\ecl\\2022.1\\IX\\bin\\intersect.exe
          C:\\Program Files\\Schlumberger\\Petrel 2022.2\\Petrel.exe
        """
        parts = exe.parts
        version = None
        install_root = None
        arch = None

        # 模式 1: <root>/<version>/bin/<arch>/exe
        for i, p in enumerate(parts):
            m = VERSION_PATTERN.match(p)
            if m:
                version = m.group(1)
                install_root = str(Path(*parts[:i + 1]))
                # 查找 bin 子目录下的架构
                if i + 2 < len(parts) and parts[i + 1].lower() == 'bin':
                    arch = parts[i + 2]
                break

        # 模式 2: 路径包含 "Petrel 2022.2"
        if version is None:
            for i, p in enumerate(parts):
                m = re.search(r'(\d{4}\.\d+)', p)
                if m and ('petrel' in p.lower() or 'eclipse' in p.lower() or 'schlumberger' in p.lower()):
                    version = m.group(1)
                    install_root = str(Path(*parts[:i + 1]))
                    break

        # 模式 3: 一般版本号
        if version is None:
            for p in parts:
                m = re.match(r'^(\d{4}\.\d+)$', p)
                if m:
                    version = m.group(1)
                    break

        install_root = install_root.replace('/', '\\') if install_root else None
        return version, install_root, arch

    # ------------------------------------------------------------
    # 去重
    # ------------------------------------------------------------

    def _dedup(self):
        seen = {}
        unique = []
        for sim in self.simulators:
            key = sim.exe_path.lower()
            if key in seen:
                self.scan_stats['duplicate_removed'] += 1
                # 保留信息更全的那条
                old = seen[key]
                if (sim.version and not old.version) or \
                   (sim.source == 'registry' and old.source == 'env'):
                    seen[key] = sim
            else:
                seen[key] = sim
                unique.append(sim)
        self.simulators = unique

    # ------------------------------------------------------------
    # 版本补全
    # ------------------------------------------------------------

    def _enrich_versions_from_path(self):
        for sim in self.simulators:
            if sim.version is None:
                v, _, _ = self._infer_version_and_root(Path(sim.exe_path))
                if v:
                    sim.version = v

    def _enrich_versions_from_file_info(self):
        """用 PowerShell 获取 exe 文件版本信息"""
        for sim in self.simulators:
            if sim.version is not None:
                continue
            try:
                r = subprocess.run(
                    ['powershell', '-NoProfile', '-NonInteractive', '-Command',
                     f"(Get-Item -LiteralPath '{sim.exe_path}').VersionInfo.ProductVersion"],
                    capture_output=True, text=True, timeout=10
                )
                v = r.stdout.strip()
                if v and v != '0.0.0.0':
                    sim.version = v
            except Exception:
                pass

    # ------------------------------------------------------------
    # License 探测
    # ------------------------------------------------------------

    def _check_license_env(self):
        """检查 license 环境变量"""
        for v in LICENSE_ENV_VARS:
            if v in os.environ and os.environ[v]:
                self.license.env_vars[v] = os.environ[v]

        # 解析 server 端口和主机
        for key, val in self.license.env_vars.items():
            # 格式: port@host 或 port@host[,port@host]
            m = re.match(r'(\d+)@([\w.\-]+)', val)
            if m:
                self.license.server_port = int(m.group(1))
                self.license.server_host = m.group(2)
                self.license.license_type = 'network'
                break
            elif val.startswith('28000') or '@' in val:
                # 网络版
                self.license.license_type = 'network'
            else:
                # 可能是 node-locked
                self.license.license_type = 'node_locked_or_unknown'

    def _check_lmutil(self):
        """查找 lmutil 并尝试 lmstat 查询"""
        candidates = []

        # 1. PATH 中的 lmutil
        path_lmutil = shutil.which('lmutil')
        if path_lmutil:
            candidates.append(path_lmutil)

        # 2. 常见安装位置
        guess_paths = [
            r"C:\ecl\home\lmutil.exe",
            r"C:\ecl\macros\lmutil.exe",
            r"C:\Program Files\Schlumberger\lmutil.exe",
            r"C:\Program Files (x86)\Schlumberger\lmutil.exe",
            r"C:\Program Files\FLEXlm\lmutil.exe",
        ]
        # 3. 从已发现的模拟器路径推断
        for sim in self.simulators:
            if sim.install_root:
                guess_paths.append(str(Path(sim.install_root) / 'bin' / 'lmutil.exe'))
                guess_paths.append(str(Path(sim.install_root) / 'home' / 'lmutil.exe'))

        for c in guess_paths:
            if c and Path(c).exists():
                candidates.append(c)

        # 去重
        seen = set()
        uniq = []
        for c in candidates:
            cl = c.lower()
            if cl not in seen:
                seen.add(cl)
                uniq.append(c)
        candidates = uniq

        for c in candidates:
            if not Path(c).exists():
                continue
            self.license.lmutil_path = c
            self.log(f"lmutil: {c}")

            # 尝试 lmstat
            if self.license.env_vars:
                lic = list(self.license.env_vars.values())[0]
                try:
                    r = subprocess.run(
                        [c, 'lmstat', '-c', lic, '-a'],
                        capture_output=True, text=True, timeout=15
                    )
                    out = r.stdout + r.stderr
                    # 截取关键摘要
                    summary_lines = []
                    for line in out.split('\n'):
                        if any(k in line.lower() for k in
                               ['server', 'license', 'feature', 'error', 'up', 'down',
                                'vendor', 'daemon', 'conn']):
                            summary_lines.append(line.strip())
                    self.license.lmstat_summary = '\n'.join(summary_lines[:30]) or out[:1500]
                except subprocess.TimeoutExpired:
                    self.warnings.append("lmutil lmstat 查询超时")
                except Exception as e:
                    self.warnings.append(f"lmutil 查询失败: {e}")
            break  # 用第一个找到的 lmutil 即可

    # ------------------------------------------------------------
    # Smoke test：最小测试案例
    # ------------------------------------------------------------

    def run_smoke_tests(self, products: Optional[List[str]] = None) -> Dict[str, dict]:
        """对所有模拟器实例跑 smoke test

        products: 限定产品列表，如 ['ECLIPSE_100', 'ECLIPSE_300']。
                  None 表示全部支持 smoke test 的产品。
        """
        supported = {'ECLIPSE_100', 'ECLIPSE_300'}  # smoke test 当前只支持这两个
        if products:
            supported = set(products) & supported

        results: Dict[str, dict] = {}
        for sim in self.simulators:
            if sim.product not in supported:
                continue
            # 同一 exe 只测一次
            key = sim.exe_path.lower()
            if key in results:
                continue
            self.log(f"smoke test: {sim.product} @ {sim.exe_path}")
            result = self._smoke_test_one(sim)
            results[key] = result
            self.scan_stats['smoke_test_runs'] += 1
            # 更新 license 总体状态
            # 关键判据：license 是否被拒绝（不是案例本身错误）
            if result.get('error') == 'license_denied':
                self.license.overall_status = 'no_license'
            elif result.get('ok'):
                # 完整通过
                if self.license.overall_status != 'no_license':
                    self.license.overall_status = 'ok'
            elif result.get('error', '').startswith('case_errors_'):
                # 案例错误但 license 通过了（能跑到 simulation 阶段）
                if self.license.overall_status != 'no_license':
                    self.license.overall_status = 'ok'
            elif result.get('error') in ('no_prt_file', 'no_ecle_end'):
                # 没生成 PRT/ECLEND → 可能是 license 问题或环境问题
                if self.license.overall_status != 'no_license':
                    self.license.overall_status = 'unknown'

        self.license.smoke_test_results = results
        return results

    def _smoke_test_one(self, sim: SimulatorInstance) -> dict:
        """运行最小测试案例"""
        result = {
            'product': sim.product,
            'exe_path': sim.exe_path,
            'ok': False,
            'duration_sec': 0.0,
            'returncode': None,
            'error': None,
            'prt_head': None,
            'outputs': [],
            'extracted_version': None,
            'extracted_build': None,
        }

        if not Path(sim.exe_path).exists():
            result['error'] = 'exe_not_found'
            return result

        with tempfile.TemporaryDirectory(prefix='ecl_smoke_') as td:
            td_path = Path(td)
            case_name = 'SMOKE'
            (td_path / f'{case_name}.DATA').write_text(
                MINIMAL_DATA_TEMPLATE, encoding='utf-8'
            )

            # 准备环境变量
            env = os.environ.copy()
            if 'SLBSLS_LICENSE_FILE' not in env:
                # 注入检测到的 license
                for v in LICENSE_ENV_VARS:
                    if v in self.license.env_vars:
                        env[v] = self.license.env_vars[v]
                        break

            t0 = time.time()
            try:
                r = subprocess.run(
                    [sim.exe_path, case_name],
                    cwd=str(td_path),
                    env=env,
                    capture_output=True,
                    text=True,
                    timeout=120,
                )
                result['duration_sec'] = round(time.time() - t0, 2)
                result['returncode'] = r.returncode

                # 解析 .PRT
                prt = td_path / f'{case_name}.PRT'
                if prt.exists():
                    head = prt.read_text(encoding='latin-1', errors='ignore')[:1500]
                    result['prt_head'] = head

                    # 检查 license 关键字（优先判断）
                    head_lower = head.lower()
                    if 'no license' in head_lower or 'flexlm error' in head_lower or \
                       'license error' in head_lower or 'cannot get license' in head_lower:
                        result['error'] = 'license_denied'
                    else:
                        # 提取版本和构建号
                        m = PRT_VERSION_PATTERN.search(head)
                        if m:
                            result['extracted_version'] = m.group(1)
                            if m.group(2):
                                result['extracted_build'] = m.group(2)
                            # 同步回 simulator
                            if not sim.version:
                                sim.version = result['extracted_version']
                            sim.build = result['extracted_build']

                    # 从 PRT 末尾提取错误/警告数（更稳健的判断）
                    try:
                        full_prt = prt.read_text(encoding='latin-1', errors='ignore')
                        # 匹配 " Errors  N" 或 "Errors                 N"
                        err_match = re.search(
                            r'^\s*Errors?\s+(\d+)\s*$', full_prt, re.MULTILINE | re.IGNORECASE
                        )
                        result['error_count_in_prt'] = int(err_match.group(1)) if err_match else None
                    except Exception:
                        result['error_count_in_prt'] = None

                    # 输出文件列表
                    outputs = sorted(f.name for f in td_path.glob(f'{case_name}.*'))
                    result['outputs'] = outputs

                    # 判断成功（三层判据）
                    ecle = td_path / f'{case_name}.ECLEND'
                    has_ecle = ecle.exists()

                    if result['error'] == 'license_denied':
                        pass  # 已设
                    elif not has_ecle:
                        result['error'] = 'no_ecle_end'
                    elif result.get('error_count_in_prt', -1) == 0:
                        result['ok'] = True
                    elif result.get('error_count_in_prt', -1) and result['error_count_in_prt'] > 0:
                        result['error'] = f'case_errors_{result["error_count_in_prt"]}'
                    else:
                        # 兜底：有 ECLEND 且无 license error，认为通过
                        result['ok'] = True
                else:
                    # .PRT 没生成 → license 失败可能性大
                    if 'license' in (r.stdout + r.stderr).lower():
                        result['error'] = 'license_denied'
                    else:
                        result['error'] = 'no_prt_file'

            except subprocess.TimeoutExpired:
                result['duration_sec'] = 120.0
                result['error'] = 'timeout'
            except Exception as e:
                result['error'] = f'exception: {e}'
                result['duration_sec'] = round(time.time() - t0, 2)

        return result


