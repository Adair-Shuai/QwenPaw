def build_report(detector: SimulatorDetector) -> DetectionReport:
    return DetectionReport(
        scan_time=time.strftime('%Y-%m-%d %H:%M:%S'),
        hostname=socket.gethostname(),
        os_version=platform.platform(),
        python_version=sys.version.split()[0],
        simulators=[s.to_dict() for s in detector.simulators],
        license=detector.license.to_dict(),
        scan_stats=detector.scan_stats,
        warnings=detector.warnings,
    )


def main():
    parser = argparse.ArgumentParser(
        description='Schlumberger 油藏模拟器自动识别与 License 验证工具',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
示例:
  %(prog)s                          标准检测
  %(prog)s --deep                   全盘深度搜索
  %(prog)s --no-smoke               跳过 smoke test
  %(prog)s --extra-root D:\\MySLB   添加自定义搜索根
  %(prog)s -v                       详细模式
        """
    )
    parser.add_argument('--deep', action='store_true',
                        help='启用全盘深度搜索（较慢，但能发现非标准路径的安装）')
    parser.add_argument('--no-smoke', action='store_true',
                        help='跳过 smoke test 验证（只检测 license 环境变量和 lmutil）')
    parser.add_argument('--only-smoke', metavar='PRODUCT',
                        help='只对指定产品跑 smoke test (ECLIPSE_100 / ECLIPSE_300)')
    parser.add_argument('--extra-root', action='append', default=[],
                        metavar='PATH', help='添加自定义搜索根目录（可多次指定）')
    parser.add_argument('--out', default='.',
                        help='报告输出目录 (默认当前目录)')
    parser.add_argument('--json', action='store_true',
                        help='输出 JSON 到终端')
    parser.add_argument('-v', '--verbose', action='store_true',
                        help='详细输出（显示检索过程）')
    args = parser.parse_args()

    print(">>> 开始检测 Schlumberger 模拟器...", file=sys.stderr)
    detector = SimulatorDetector(
        verbose=args.verbose,
        deep=args.deep,
        extra_roots=args.extra_root,
    )
    detector.detect_all()

    if not args.no_smoke:
        products = [args.only_smoke] if args.only_smoke else None
        print(">>> 运行 smoke test...", file=sys.stderr)
        detector.run_smoke_tests(products=products)

    report = build_report(detector)

    out_dir = Path(args.out).absolute()
    out_dir.mkdir(parents=True, exist_ok=True)
    txt_path = out_dir / 'simulator_report.txt'
    json_path = out_dir / 'simulator_report.json'
    txt_path.write_text(format_text_report(report), encoding='utf-8')
    json_path.write_text(format_json_report(report), encoding='utf-8')

    if args.json:
        print(format_json_report(report))
    else:
        print(format_text_report(report))

    print(f"\n>>> 文本报告: {txt_path}", file=sys.stderr)
    print(f">>> JSON 报告: {json_path}", file=sys.stderr)
    print(f">>> 共检测到 {len(report.simulators)} 个模拟器", file=sys.stderr)


if __name__ == '__main__':
    main()
