def format_text_report(report: DetectionReport) -> str:
    """生成可读文本报告"""
    lines = []
    sep = '=' * 72

    lines.append(sep)
    lines.append("  Schlumberger 油藏模拟器检测报告")
    lines.append(sep)
    lines.append(f"  扫描时间 : {report.scan_time}")
    lines.append(f"  主机名   : {report.hostname}")
    lines.append(f"  操作系统 : {report.os_version}")
    lines.append(f"  Python   : {report.python_version}")
    lines.append(f"  扫描耗时 : {report.scan_stats.get('duration_sec', 0)} 秒")
    lines.append("")

    # ---- 模拟器列表 ----
    lines.append(sep)
    lines.append("  一、模拟器检测结果")
    lines.append(sep)
    if not report.simulators:
        lines.append("  未检测到任何 Schlumberger 模拟器。")
        lines.append("  建议：")
        lines.append("    1. 检查软件是否已安装")
        lines.append("    2. 使用 --deep 参数进行全盘深度搜索")
        lines.append("    3. 使用 --extra-root <path> 添加自定义搜索根")
    else:
        lines.append(f"  共检测到 {len(report.simulators)} 个模拟器实例：")
        lines.append("")
        # 按产品分组
        by_product: Dict[str, List[dict]] = {}
        for s in report.simulators:
            by_product.setdefault(s['product'], []).append(s)

        product_order = ['ECLIPSE_100', 'ECLIPSE_300', 'INTERSECT',
                         'FRONTSIM', 'VISAGE', 'PETREL', 'ECLRUN']
        for product in product_order:
            if product not in by_product:
                continue
            instances = by_product[product]
            lines.append(f"  [{product}]  ({len(instances)} 个)")
            for i, s in enumerate(instances, 1):
                lines.append(f"    #{i} {s['exe_path']}")
                lines.append(f"        版本   : {s.get('version') or '未知'}"
                             + (f" (Build {s['build']})" if s.get('build') else ""))
                lines.append(f"        架构   : {s.get('arch') or '-'}")
                lines.append(f"        安装根 : {s.get('install_root') or '-'}")
                lines.append(f"        来源   : {s.get('source', 'unknown')}"
                             + (f"  大小: {s['file_size_mb']} MB" if s.get('file_size_mb') else ""))
            lines.append("")

    # ---- License 状态 ----
    lines.append(sep)
    lines.append("  二、License 状态")
    lines.append(sep)
    lic = report.license
    if lic.get('overall_status') == 'ok':
        lines.append(f"  总体状态 : OK (绿色)")
    elif lic.get('overall_status') == 'no_license':
        lines.append(f"  总体状态 : License 不可用 (红色)")
    else:
        lines.append(f"  总体状态 : 未知 (建议运行 smoke test 验证)")

    lines.append("")
    lines.append("  环境变量：")
    if lic.get('env_vars'):
        for k, v in lic['env_vars'].items():
            lines.append(f"    {k} = {v}")
    else:
        lines.append("    (无 license 相关环境变量)")

    if lic.get('server_host') or lic.get('server_port'):
        lines.append("")
        lines.append(f"  License Server : {lic.get('server_port')}@{lic.get('server_host')}")
        lines.append(f"  License 类型   : {lic.get('license_type', 'unknown')}")

    lines.append("")
    lines.append(f"  lmutil 路径 : {lic.get('lmutil_path') or '(未找到)'}")
    if lic.get('lmstat_summary'):
        lines.append("")
        lines.append("  lmstat 摘要：")
        for line in lic['lmstat_summary'].split('\n')[:15]:
            lines.append(f"    {line}")

    # ---- Smoke test 结果 ----
    if lic.get('smoke_test_results'):
        lines.append("")
        lines.append(sep)
        lines.append("  三、Smoke Test 验证结果")
        lines.append(sep)
        for key, res in lic['smoke_test_results'].items():
            status = "PASS" if res.get('ok') else "FAIL"
            icon = "[OK]" if res.get('ok') else "[X]"
            lines.append(f"  {icon} {res.get('product')} @ {key}")
            lines.append(f"      状态      : {status}")
            lines.append(f"      耗时      : {res.get('duration_sec', 0)} 秒")
            lines.append(f"      退出码    : {res.get('returncode')}")
            if res.get('error'):
                lines.append(f"      错误      : {res['error']}")
            if res.get('error_count_in_prt') is not None:
                lines.append(f"      PRT错误数: {res['error_count_in_prt']}")
            if res.get('extracted_version'):
                lines.append(f"      版本(PRT) : {res['extracted_version']}"
                             + (f" Build {res['extracted_build']}" if res.get('extracted_build') else ""))
            if res.get('outputs'):
                lines.append(f"      输出文件  : {', '.join(res['outputs'])}")

    # ---- 警告 ----
    if report.warnings:
        lines.append("")
        lines.append(sep)
        lines.append("  四、警告")
        lines.append(sep)
        for w in report.warnings:
            lines.append(f"  [!] {w}")

    # ---- 扫描统计 ----
    lines.append("")
    lines.append(sep)
    lines.append("  五、扫描统计")
    lines.append(sep)
    for k, v in report.scan_stats.items():
        lines.append(f"  {k:25s} : {v}")

    lines.append("")
    lines.append(sep)
    lines.append("  报告结束")
    lines.append(sep)
    return '\n'.join(lines)


def format_json_report(report: DetectionReport) -> str:
    return json.dumps(report.to_dict(), indent=2, ensure_ascii=False)


