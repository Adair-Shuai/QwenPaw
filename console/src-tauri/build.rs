fn main() {
    // These are the parts a component ZIP cannot replace. Match component_host.py.
    use sha2::{Digest, Sha256};
    use std::path::{Path, PathBuf};
    fn collect(path: &Path, files: &mut Vec<PathBuf>) {
        if path.is_dir() {
            for entry in std::fs::read_dir(path).expect("read host inputs") {
                collect(&entry.expect("host input").path(), files);
            }
        } else if path.is_file() {
            files.push(path.to_owned());
        }
    }
    let root = Path::new("../..");
    let mut files = Vec::new();
    for name in [
        "console/src-tauri/src",
        "console/src-tauri/build.rs",
        "console/src-tauri/Cargo.toml",
        "console/src-tauri/Cargo.lock",
        "console/src-tauri/capabilities",
        "console/src-tauri/permissions",
        "scripts/pack/assets/icon.svg",
        "console/src-tauri/nsis",
        "console/src-tauri/nsis-hooks.nsh",
        "console/src-tauri/nsis-languages",
        "console/src-tauri/vite.bootstrap.config.ts",
        "console/buildVersion.ts",
        "console/src-tauri/tauri.conf.json",
        "console/src",
        "console/package.json",
        "console/package-lock.json",
        "console/tauri.html",
        "console/vite.config.ts",
    ] {
        println!("cargo:rerun-if-changed={}", root.join(name).display());
        collect(&root.join(name), &mut files);
    }
    files.sort_by_key(|path| {
        path.strip_prefix(root)
            .unwrap()
            .to_string_lossy()
            .replace('\\', "/")
    });
    let mut digest = Sha256::new();
    for path in files {
        digest.update(
            path.strip_prefix(root)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/")
                .as_bytes(),
        );
        digest.update([0]);
        let bytes = std::fs::read(path).expect("read host input");
        let normalized: Vec<u8> = bytes
            .iter()
            .enumerate()
            .filter(|(i, byte)| !(**byte == b'\r' && bytes.get(i + 1) == Some(&b'\n')))
            .map(|(_, byte)| *byte)
            .collect();
        digest.update(normalized);
        digest.update([0]);
    }
    println!(
        "cargo:rustc-env=QWENPAW_HOST_FINGERPRINT={:x}",
        digest.finalize()
    );
    // The Tauri bootstrap is generated by `build:tauri-bootstrap`. Raw
    // `cargo build` is also used by the packaging and local replacement
    // flows, so make the generated frontend an explicit build input rather
    // than silently reusing a binary that embedded an older (or empty)
    // bootstrap directory.
    println!("cargo:rerun-if-changed=../dist-tauri");
    // `cargo check`/`cargo test` validate Tauri resources before the packaging
    // scripts have generated the PyInstaller sidecar. Keep release builds strict
    // while allowing local Rust checks to run in a clean checkout.
    if std::env::var("PROFILE").as_deref() != Ok("release") {
        let _ = std::fs::create_dir_all("binaries/qwenpaw-backend");
        let _ = std::fs::create_dir_all("binaries/officecli");
        let _ = std::fs::create_dir_all("binaries/java-runtime");
        let _ = std::fs::create_dir_all("binaries/neqsim");
    }

    tauri_build::build()
}
